#!/bin/bash

# ---------------------------------------------------
# 08_exit_codes.sh
# Bash Exit Codes
# ---------------------------------------------------
echo
echo "=============================================="
echo "             BASH EXIT CODES"
echo "=============================================="


# ---------------------------------------------------
# 1. Successful command
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "1. Successful Command"
echo "----------------------------------------------"

echo "Hello from Bash"

echo "Exit code: $?"


# ---------------------------------------------------
# 2. Failed command
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "2. Failed Command"
echo "----------------------------------------------"

ls /directory_that_does_not_exist

echo "Exit code: $?"


# ---------------------------------------------------
# 3. Store exit code
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "3. Store Exit Code"
echo "----------------------------------------------"

ls /tmp

status=$?

echo "Command exit code: $status"


# ---------------------------------------------------
# 4. if with exit code
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "4. Check Exit Code"
echo "----------------------------------------------"

if ls /tmp > /dev/null 2>&1
then
    echo "Command executed successfully"
else
    echo "Command failed"
fi


# ---------------------------------------------------
# 5. Function exit code
# ---------------------------------------------------

check_number()
{
    if [ "$1" -gt 10 ]
    then
        return 0
    else
        return 1
    fi
}

echo
echo "----------------------------------------------"
echo "5. Function Exit Code"
echo "----------------------------------------------"

if check_number 20
then
    echo "Number is greater than 10"
else
    echo "Number is not greater than 10"
fi


# ---------------------------------------------------
# 6. Custom exit code
# ---------------------------------------------------

check_file()
{
    if [ -f "$1" ]
    then
        return 0
    else
        return 2
    fi
}

echo
echo "----------------------------------------------"
echo "6. Custom Exit Code"
echo "----------------------------------------------"

check_file "/etc/passwd"

status=$?

echo "Exit code: $status"


# ---------------------------------------------------
# 7. Exit command
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "7. Exit Command"
echo "----------------------------------------------"

exit_demo()
{
    echo "Function completed successfully"
    return 0
}

exit_demo

echo "Function exit code: $?"


# ---------------------------------------------------
# 8. Logical AND
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "8. Logical AND"
echo "----------------------------------------------"

true && echo "First command succeeded"


# ---------------------------------------------------
# 9. Logical OR
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "9. Logical OR"
echo "----------------------------------------------"

false || echo "First command failed"


# ---------------------------------------------------
# 10. Script exit
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "10. Script Exit"
echo "----------------------------------------------"

echo "Script completed successfully"

exit 0



