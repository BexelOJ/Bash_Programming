#!/bin/bash

# ---------------------------------------------------
# 10_system_info.sh
# Linux System Information
# ---------------------------------------------------

echo "=============================================="
echo "          LINUX SYSTEM INFORMATION"
echo "=============================================="


# ---------------------------------------------------
# 1. Hostname
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "1. Hostname"
echo "----------------------------"

echo "Hostname: $(hostname)"


# ---------------------------------------------------
# 2. Kernel information
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "2. Kernel Information"
echo "----------------------------"

uname -a


# ---------------------------------------------------
# 3. Kernel version
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "3. Kernel Version"
echo "----------------------------"

echo "Kernel: $(uname -r)"


# ---------------------------------------------------
# 4. Operating system
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "4. Operating System"
echo "----------------------------"

if [ -f /etc/os-release ]
then
    source /etc/os-release

    echo "Name    : $NAME"
    echo "Version : $VERSION"
    echo "ID      : $ID"
fi


# ---------------------------------------------------
# 5. Architecture
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "5. Architecture"
echo "----------------------------"

echo "Architecture: $(uname -m)"


# ---------------------------------------------------
# 6. CPU information
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "6. CPU Information"
echo "----------------------------"

echo "CPU Cores: $(nproc)"

echo
echo "CPU Model:"
grep "model name" /proc/cpuinfo | head -1


# ---------------------------------------------------
# 7. Memory information
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "7. Memory Information"
echo "----------------------------"

free -h


# ---------------------------------------------------
# 8. Disk information
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "8. Disk Information"
echo "----------------------------------------------"

df -h


# ---------------------------------------------------
# 9. System uptime
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "9. System Uptime"
echo "----------------------------"

uptime


# ---------------------------------------------------
# 10. Current user
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "10. Current User"
echo "----------------------------"

echo "User: $(whoami)"


# ---------------------------------------------------
# 11. Current directory
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "11. Current Directory"
echo "----------------------------"

echo "Directory: $(pwd)"


# ---------------------------------------------------
# 12. Logged-in users
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "12. Logged-in Users"
echo "----------------------------"

who


# ---------------------------------------------------
# 13. Network information
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "13. Network Information"
echo "----------------------------"

ip -brief address


# ---------------------------------------------------
# 14. Default gateway
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "14. Default Gateway"
echo "----------------------------"

ip route | grep default


# ---------------------------------------------------
# 15. Running processes
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "15. Running Processes"
echo "----------------------------"

process_count=$(ps -e --no-headers | wc -l)

echo "Running processes: $process_count"


# ---------------------------------------------------
# 16. Current date and time
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "16. Date and Time"
echo "----------------------------"

date


# ---------------------------------------------------
# 17. Shell
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "17. Current Shell"
echo "----------------------------"

echo "Shell: $SHELL"


# ---------------------------------------------------
# 18. Bash version
# ---------------------------------------------------
echo
echo "----------------------------------------------"
echo "18. Bash Version"
echo "----------------------------"

echo "Bash version: $BASH_VERSION"


# ---------------------------------------------------
# End
# ---------------------------------------------------

echo
echo "=============================================="
echo "     SYSTEM INFORMATION DEMO COMPLETED"
echo "=============================================="



